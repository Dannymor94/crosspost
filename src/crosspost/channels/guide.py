"""Инструкции подключения — часть ДЕКЛАРАЦИИ канала (не хардкод в UI).

Тон — дружеский, на «вы», без техжаргона (аудитория: клиенты-нетехнари).
Каждый канал приносит свою инструкцию сам: ChannelValidatorDef.guide ссылается
на константу отсюда. Новый канал → добавил ChannelGuide → UI сам её покажет.

Структура (что рисует фронт):
  intro        — короткий дружеский абзац: что подключаем и как это работает.
  blocks       — раскрывашки «Как это получить?» (по умолчанию свёрнуты). Блок с
                 field="" — общий (вверху формы); field="api_id" — под этим полем.
  step_hints   — подсказка на каждом шаге интерактивного входа (Telegram: что
                 сейчас произойдёт и что делать). key = имя шага степпера.
  browser_note — для браузерных каналов: что откроется окно, надо войти, «Я вошёл».
  errors       — что проверить при ошибке (симптом → совет).
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class GuideBlock:
    """Раскрывающийся блок «Как это получить?»: заголовок + шаги + ссылка."""

    label: str  # текст-раскрывашка, напр. «Как получить api_id и api_hash?»
    steps: tuple[str, ...]  # пронумерованные человеческие шаги
    link: str = ""  # прямая ссылка «куда идти»
    link_label: str = ""  # подпись ссылки (по умолчанию — «открыть →»)
    field: str = ""  # "" = общий блок формы; иначе привязан к полю с этим name


@dataclass(frozen=True)
class StepHint:
    """Подсказка на конкретном шаге интерактивного входа."""

    key: str  # имя шага степпера: form|phone|code|password
    text: str  # что сейчас произойдёт / что делать


@dataclass(frozen=True)
class ErrorHint:
    """Что проверить при типичной ошибке подключения."""

    symptom: str  # как выглядит проблема
    check: str  # что проверить/сделать


@dataclass(frozen=True)
class ChannelGuide:
    """Полная инструкция подключения одного канала (живёт в декларации)."""

    intro: str = ""
    blocks: tuple[GuideBlock, ...] = ()
    step_hints: tuple[StepHint, ...] = ()
    browser_note: str = ""
    errors: tuple[ErrorHint, ...] = field(default_factory=tuple)


